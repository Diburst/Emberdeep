function F.build()
  local n = #defs
  local imgW = n * (W + 1) + 1
  local data = love.image.newImageData(imgW, H)
  -- separator = magenta
  local sr, sg, sb = 1, 0, 1
  for y = 0, H - 1 do data:setPixel(0, y, sr, sg, sb, 1) end
  local glyphs = {}
  local x0 = 1
  for _, def in ipairs(defs) do
    glyphs[#glyphs + 1] = def[1]
    local rows = def[2]
    for ry = 1, H do
      local row = rows[ry]
      for rx = 1, W do
        local on = row:sub(rx, rx) == "#"
        if on then
          data:setPixel(x0 + rx - 1, ry - 1, 1, 1, 1, 1)
        else
          data:setPixel(x0 + rx - 1, ry - 1, 0, 0, 0, 0)
        end
      end
    end
    -- separator column after glyph
    for y = 0, H - 1 do data:setPixel(x0 + W, y, sr, sg, sb, 1) end
    x0 = x0 + W + 1
  end
  local font = love.graphics.newImageFont(data, table.concat(glyphs), 1)
  font:setLineHeight(1.35)
  G.fonts = { main = font }
  love.graphics.setFont(font)
end

return F
