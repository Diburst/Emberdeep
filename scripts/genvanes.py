# 2. THE UPPER GALLERY -- gal_1 / gal_2 / gal_3, behind the vanes gate
# ==================================================================
def build_gallery():
    # ---- sky_2: a sealed pocket behind a full-height driftvanes gate.
    # Same shape as scrap_6's gate, which validated: the column genuinely
    # separates, and the pocket contains its own door so it is not a trap.
    def f(g, s):
        for y in range(2, 12):
            assert g[y][4] == ".", (y, g[y][:8])
            g[y][4] = "G"
        for y in (10, 11):
            g[y][2] = g[y][3] = "C"
        s = s.replace('  mapPos = { x = 0, y = 2, w = 3, h = 1 },',
                      '  mapPos = { x = 0, y = 2, w = 3, h = 1 },\n'
                      '  gates = { G = "driftvanes" },', 1)
        return s.replace('    E = { "sky_secret", "A" },',
                         '    E = { "sky_secret", "A" },\n'
                         '    C = { "gal_1", "A" },', 1)
    patch_map("sky_2", f)
    print("  patched sky_2: driftvanes gate + portal C -> gal_1")

    # ---- gal_1 THE SPAN. 30 wide on purpose: exactly one screen, so the
    # camera never scrolls and the pair cannot be split (see the plan, 5.3).
    # An 11-tile gap at the upper level; missing it drops you to the floor
    # and costs a climb, not health.
    r = R("gal_1", 30, 17, 12)
    r.portal("A", 3, y0=6)
    r.doorR("B", y0=6)
    r.put(2, 8, "#######")        # left platform  (stand row 7, cols 2-8)
    r.put(20, 8, "########")      # right platform (stand row 7, cols 20-27)
    r.put(9, 10, "===")           # the climb back out of the pit
    r.put(24, 11, "1")
    write_room(r, mapPos=(0, 1, 1, 1),
               key={"1": "sign:sign_span"},
               links={"A": ("sky_2", "C"), "B": ("gal_2", "A")})

    # ---- gal_2 THE COMBS. Two stacked thermal columns, 12 and 10 tiles,
    # with a shared landing between them. Both are inside the 12.7-tile
    # vertical camera budget, so Vess watches her the whole way up.
    # No anchors in this room: this is the gated wing.
    r = R("gal_2", 30, 34, 32)
    r.doorL("A", y0=30)
    r.doorR("B", y0=10)
    r.put(9, 21, "################")   # mid landing (stand row 20, cols 9-24)
    r.put(21, 12, "#######")           # top landing (stand row 11, cols 21-27)
    r.put(8, 31, "U")                  # column 1: rows 20..31
    r.put(20, 20, "u")                 # column 2: rows 11..20
    r.put(4, 31, "z")
    r.put(12, 20, "y")                 # windray on the mid landing
    r.put(23, 11, "q")                 # stormvane on the top landing
    r.put(16, 20, "y")
    write_room(r, mapPos=(1, 0, 1, 2),
               key={"U": "updraft:12", "u": "updraft:10", "z": "checkpoint",
                    "y": "windray", "q": "stormvane"},
               links={"A": ("gal_1", "B"), "B": ("gal_3", "A")})

    # ---- gal_3 THE LONG ROOM. Lockers, a roster, and the tank.
    r = R("gal_3", 60, 17, 12)
    r.doorL("A")
    r.put(10, 8, "======")
    r.put(30, 7, "=======")
    r.put(44, 9, "======")
    r.put(8, 11, "1")
    r.put(20, 11, "2")
    r.put(34, 11, "3")
    r.put(50, 11, "4")
    r.put(46, 8, "z")
    write_room(r, mapPos=(2, 0, 3, 1),
               key={"1": "sign:sign_roster1", "2": "sign:sign_roster2",
                    "3": "sign:sign_roster3", "4": "tank:tank_gallery",
                    "z": "checkpoint"},
               links={"A": ("gal_2", "B")})


