#!/usr/bin/env python3
"""Build THE DRIFT VANES content: the Nest, the Upper Gallery, and the
eight retrofits.

Run from game/ with PYTHONPATH=../scripts.

The retrofits do not use hand-picked coordinates. For each target room the
script asks roommodel which cells are reachable WITH the vanes and not
without, filters to the ones that are standable and free, scores them by
the co-op camera budget, and puts the reward on the best one. If a room
has no legal hover-only cell it says so instead of guessing.
"""
import os
import re
import sys
import roommodel as RM

ROOMS = "src/data/rooms"
VW, VH, T = RM.viewport()  # read out of main.lua, never copied
H_BUDGET, V_BUDGET = 0.75 * VW / T, 0.75 * VH / T


# ==================================================================
# room construction helpers (same shape as genscrap.py)
# ==================================================================
class R:
    def __init__(self, name, w, h, floor):
        self.name, self.W, self.H, self.floor = name, w, h, floor
        self.g = [["#"] * w for _ in range(h)]
        for y in range(2, floor):
            for x in range(2, w - 2):
                self.g[y][x] = "."

    def put(self, x, y, s):
        for i, c in enumerate(s):
            self.g[y][x + i] = c

    def col(self, x, y0, y1, c):
        for y in range(y0, y1 + 1):
            self.g[y][x] = c

    def doorL(self, ch, y0=None):
        y0 = self.floor - 2 if y0 is None else y0
        for y in (y0, y0 + 1):
            self.g[y][0] = ch; self.g[y][1] = ch

    def doorR(self, ch, y0=None):
        y0 = self.floor - 2 if y0 is None else y0
        for y in (y0, y0 + 1):
            self.g[y][self.W - 2] = ch; self.g[y][self.W - 1] = ch

    def portal(self, ch, x, y0=None):
        y0 = self.floor - 2 if y0 is None else y0
        for y in (y0, y0 + 1):
            self.g[y][x] = ch; self.g[y][x + 1] = ch

    def rows(self):
        return ["".join(r) for r in self.g]


def write_room(r, *, mapPos, links, key=None, gates=None, zone="skyroot",
               music="skyroot", extra=None):
    rows = r.rows()
    w = len(rows[0])
    for i, row in enumerate(rows):
        assert len(row) == w, (r.name, i, len(row))
    out = ["-- generated by scripts/genvanes.py (The Drift Vanes)", "return {"]
    out.append('  zone = "%s", music = "%s",' % (zone, music))
    out.append("  mapPos = { x = %d, y = %d, w = %d, h = %d }," % mapPos)
    for e in (extra or []):
        out.append(e)
    if gates:
        out.append("  gates = { " + ", ".join('%s = "%s"' % kv
                                              for kv in gates.items()) + " },")
    out.append("  map = [[")
    out += rows
    out.append("]],")
    if key:
        out.append("  key = {")
        for k, v in key.items():
            out.append('    ["%s"] = "%s",' % (k, v))
        out.append("  },")
    out.append("  links = {")
    for k, v in links.items():
        out.append('    %s = { "%s", "%s" },' % (k, v[0], v[1]))
    out.append("  },")
    out.append("}")
    open(os.path.join(ROOMS, r.name + ".lua"), "w").write("\n".join(out) + "\n")
    print("  wrote %-13s %dx%d" % (r.name, w, len(rows)))


def patch_map(name, fn):
    """Read a room's map, hand the grid to fn, write it back."""
    p = os.path.join(ROOMS, name + ".lua")
    s = open(p).read()
    m = re.search(r"map = \[\[\n(.*?)\]\]", s, re.S)
    g = [list(r) for r in m.group(1).split("\n") if r.strip()]
    W = len(g[0])
    s2 = fn(g, s)
    if s2 is not None:
        s = s2
    rows = ["".join(r) for r in g]
    for r in rows:
        assert len(r) == W, (name, len(r), W)
    m = re.search(r"map = \[\[\n(.*?)\]\]", s, re.S)
    s = s[:m.start(1)] + "\n".join(rows) + "\n" + s[m.end(1):]
    open(p, "w").write(s)


# ==================================================================
# 1. THE NEST -- sky_nest, off sky_4
# ==================================================================
def build_nest():
    r = R("sky_nest", 30, 17, 12)
    r.doorL("A")
    r.put(6, 8, "=====")
    r.put(18, 6, "======")
    r.put(9, 11, "1")          # the Perch 2 notice
    r.put(15, 11, "N")         # the nest itself
    r.put(17, 11, "3")         # the vanes, in it (NOT "v": that is SPIKE_D)
    write_room(r, mapPos=(7, 1, 1, 1),
               key={"1": "sign:sign_perch2", "N": "nest",
                    "3": "chest:chest_driftvanes:module:driftvanes"},
               links={"A": ("sky_4", "C")})

    # sky_4 gets door C on the right edge, rows 4-5: the shelf at row 5 is
    # already standable (the checkpoint sits on it) and row 6 under it is
    # solid, so the door needs no new geometry at all.
    def f(g, s):
        for y in (4, 5):
            assert g[y][28] == "#" and g[y][29] == "#", (y, g[y][26:])
            g[y][28] = g[y][29] = "C"
        assert g[6][28] == "#" and g[6][27] == "#", "shelf under the door"
        return s.replace('    B = { "sky_boss", "A" },',
                         '    B = { "sky_boss", "A" },\n'
                         '    C = { "sky_nest", "A" },', 1)
    patch_map("sky_4", f)
    print("  patched sky_4: door C -> sky_nest")


