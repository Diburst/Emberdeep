# 3. THE RETROFITS -- the model picks the cell, not me
# ==================================================================
RETROFITS = [
    # room,        char, spec,                              preferred side
    ("cradle_1",   "N",  "sign:sign_sleepers",              None),
    ("moss_5",     "9",  "chest:ch_moss_high:scrap:20",     None),
    ("flood_2",    "T",  "tank:tank_flood",                 None),
    ("furn_4",     "9",  "chest:ch_furn_high:bigshard:6",   None),
    ("cold_1",     "9",  "chest:ch_cold_high:bigshard:6",   None),
    ("crys_boss",  "9",  "chest:ch_crys_high:scrap:25",     None),
    ("sky_boss",   "9",  "chest:ch_roost:bigshard:8",       None),
    ("camp_awake", "9",  "chest:ch_shelf:scrap:15",         None),
]


def hover_only_cells(room):
    def reach(with_vanes):
        flags = set(RM.ALL_ABILITIES)
        if not with_vanes:
            flags.discard("driftvanes")
        for ch, f in room.gates.items():
            f = f[1:] if f.startswith("!") else f
            if not with_vanes and f == "driftvanes":
                continue
            flags.add(f)
        nav = RM.Nav(room, flags)
        if not room.doors:
            return set()
        start = set()
        for ch in room.doors:
            start |= set(nav.arrivals(ch)) | set(room.doors[ch])
        return nav.reach_from(start)
    without, withv = reach(False), reach(True)
    return without, withv - without


def do_retrofits():
    for name, ch, spec, _side in RETROFITS:
        room = RM.parse_room(os.path.join(ROOMS, name + ".lua"))
        without, gated = hover_only_cells(room)
        h_scroll = room.W * T > VW
        v_scroll = room.H * T > VH
        occupied = {c for cells in (room.spawns or {}).values() for c in cells}
        best, best_score = None, None
        for (x, y) in sorted(gated):
            if (x, y) in occupied:
                continue
            nav = RM.Nav(room, set(RM.ALL_ABILITIES))
            if not nav.standable(x, y):
                continue
            if ch in room.key:            # char already used for something else
                continue
            # co-op cost: how far from the nearest place Vess can stand
            dh = min(abs(x - ax) for (ax, ay) in without) if without else 0
            dv = min(abs(y - ay) for (ax, ay) in without) if without else 0
            if h_scroll and dh > H_BUDGET:
                continue
            if v_scroll and dv > V_BUDGET:
                continue
            score = (dh + dv, -x)         # prefer the tightest, then leftmost
            if best_score is None or score < best_score:
                best, best_score = (x, y), score
        if not best:
            print("  SKIP %-12s no legal hover-only cell inside the co-op budget"
                  % name)
            continue
        bx, by = best

        def f(g, s, bx=bx, by=by, ch=ch, spec=spec):
            assert g[by][bx] == ".", (name, bx, by, g[by][bx])
            g[by][bx] = ch
            if "key = {" in s:
                return s.replace("  key = {",
                                 '  key = {\n    ["%s"] = "%s",' % (ch, spec), 1)
            return s.replace("  links = {",
                             '  key = {\n    ["%s"] = "%s",\n  },\n  links = {'
                             % (ch, spec), 1)
        patch_map(name, f)
        print("  %-12s '%s' at %-9s  (%d h / %d v tiles from Vess)"
              % (name, ch, str(best), best_score[0] - 0, 0))


def main():
    print("THE NEST")
    build_nest()
    print("THE UPPER GALLERY")
    build_gallery()
    print("RETROFITS")
    do_retrofits()
    print("done")


if __name__ == "__main__":
    main()
